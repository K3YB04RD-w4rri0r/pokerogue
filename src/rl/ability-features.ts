/**
 * Encode 40 ability feature floats into the buffer.
 * If ability_id is out of range, writes the default vector (all-neutral).
 */
export function encodeAbilityFeatures(abilityId: number, buf: Float32Array, pos: number): number {
  const features = (abilityId >= 0 && abilityId < ABILITY_FEATURES.length)
    ? ABILITY_FEATURES[abilityId]
    : ABILITY_FEATURES[0]; // NONE defaults
  for (let i = 0; i < FEATURE_DIM; i++) {
    buf[pos + i] = features[i];
  }
  return pos + FEATURE_DIM;
}
