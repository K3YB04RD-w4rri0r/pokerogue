describe("encoder-data single-source gate", () => {
  it("checked-in generated/encoder-data.json matches the live TS modules", () => {
    const payload = buildPayload();
    const rendered = `${JSON.stringify(payload, null, 2)}\n`;

    if (process.env.UPDATE_RL_ENCODER_DATA) {
      fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
      fs.writeFileSync(OUT_PATH, rendered);
      console.log(`regenerated ${OUT_PATH}`);
      return;
    }

    expect(fs.existsSync(OUT_PATH), `missing ${OUT_PATH} — regenerate with UPDATE_RL_ENCODER_DATA=1`).toBe(true);
    const checkedIn = fs.readFileSync(OUT_PATH, "utf8");
    expect(checkedIn, "generated encoder-data.json is STALE — regenerate with UPDATE_RL_ENCODER_DATA=1").toBe(rendered);
  });

  it("payload sanity: table shapes match the declared dims", () => {
    const payload = buildPayload() as Record<string, any>;
    expect(payload.ability_features).toHaveLength(311);
    for (const row of payload.ability_features) {
      expect(row).toHaveLength(FEATURE_DIM);
    }
    for (const vec of Object.values(payload.modifier_features) as number[][]) {
      expect(vec).toHaveLength(MODIFIER_FEATURE_DIM);
    }
    expect(payload.type_effectiveness).toHaveLength(spaces.NUM_POKEMON_TYPES);
    expect(payload.curated_volatile_tags).toHaveLength(spaces.NUM_CURATED_TAGS);
    expect(payload.arena_tag_order).toHaveLength(spaces.NUM_ARENA_TAG_TYPES);
    expect(payload.stage_multipliers).toHaveLength(13);
    // block layout must tile [0, OBSERVATION_DIM) exactly
    const blocks = payload.block_layout as { name: string; base: number; dim: number }[];
    const end = blocks.reduce((pos, b) => {
      expect(b.base).toBe(pos);
      return pos + b.dim;
    }, 0);
    expect(end).toBe(spaces.OBSERVATION_DIM);
  });
});
