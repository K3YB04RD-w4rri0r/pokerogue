/** Numeric-enum members as {NAME: value}, dropping TS reverse mappings. */
function numericEnum(e: Record<string, unknown>): Record<string, number> {
  const out: Record<string, number> = {};
  for (const [k, v] of Object.entries(e)) {
    if (typeof v === "number") {
      out[k] = v;
    }
  }
  return out;
}

/** String-enum members as {NAME: value}. */
function stringEnum(e: Record<string, unknown>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(e)) {
    if (typeof v === "string") {
      out[k] = v;
    }
  }
  return out;
}

