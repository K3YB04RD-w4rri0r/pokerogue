/**
 * Single-source gate for the dual-encoder DATA (see
 * src/rl/docs/ENCODER_SINGLE_SOURCE_PROPOSAL.md, Phase 1).
 *
 * Serializes every table/constant the Python mirror needs from the LIVE TS
 * modules (the wire authority) into src/rl/generated/encoder-data.json and
 * asserts the checked-in artifact matches — so the generated data can never
 * go stale without failing the ordinary vitest gate (rl-verify V11 / CI).
 *
 * To regenerate after intentionally changing encoder tables:
 *
 *   UPDATE_RL_ENCODER_DATA=1 pnpm exec vitest run test/rl/encoder-data-sync.test.ts
 *
 * The Python side loads this JSON via src/rl/encoder_data.py; cross-language
 * equality of the ENCODERS (logic) is separately proven bitwise by the golden
 * fixtures + tools/verify/check_parity.py.
 */

